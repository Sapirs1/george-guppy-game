// --- Tests -------------------------------------------------------------------

describe('gameHelpers', () => {
  describe('formatUiText', () => {
    it('formats the level name and remaining bubble count', () => {
      expect(formatUiText('Strange Tank', 3)).toBe('Level: Strange Tank\nBubbles: 3');
    });

    it('formats zero bubbles correctly', () => {
      expect(formatUiText('Homecoming', 0)).toBe('Level: Homecoming\nBubbles: 0');
    });
  });

  describe('clampLevelIndex', () => {
    it('clamps negative indexes to 0', () => {
      expect(clampLevelIndex(-1, 4)).toBe(0);
    });

    it('clamps too-high indexes to the last valid index', () => {
      expect(clampLevelIndex(10, 4)).toBe(3);
    });

    it('keeps valid indexes unchanged', () => {
      expect(clampLevelIndex(2, 5)).toBe(2);
    });

    it('returns 0 when no levels are available', () => {
      expect(clampLevelIndex(5, 0)).toBe(0);
    });
  });

  describe('validateLevelData', () => {
    const textures = ['bg_strange_tank', 'snail', 'drain'];

    const baseLevel              = {
      id: 99,
      name: 'Test Tank',
      backgroundKey: 'bg_strange_tank',
      width: 800,
      height: 600,
      playerStart: { x: 400, y: 300 },
      walls: [],
      bubbles: [],
      npcs: [{ x: 100, y: 100, texture: 'snail', dialogKey: 'snail_intro' }],
    };

    it('returns no errors for a valid level', () => {
      expect(validateLevelData([baseLevel], realDialogues, textures)).toEqual([]);
    });

    it('reports a missing backgroundKey', () => {
      const bad = { ...baseLevel, backgroundKey: 'missing_bg' };
      const errors = validateLevelData([bad], realDialogues, textures);
      expect(errors.length).toBe(1);
      expect(errors[0]).toContain('missing background texture');
      expect(errors[0]).toContain('missing_bg');
    });

    it('reports a missing NPC texture', () => {
      const bad              = {
        ...baseLevel,
        npcs: [{ x: 0, y: 0, texture: 'missing_npc', dialogKey: 'snail_intro' }],
      };
      const errors = validateLevelData([bad], realDialogues, textures);
      expect(errors.some((e) => e.includes('missing NPC texture'))).toBe(true);
      expect(errors.some((e) => e.includes('missing_npc'))).toBe(true);
    });

    it('reports a missing dialogKey', () => {
      const bad              = {
        ...baseLevel,
        npcs: [{ x: 0, y: 0, texture: 'snail', dialogKey: 'no_such_dialog' }],
      };
      const errors = validateLevelData([bad], realDialogues, textures);
      expect(errors.some((e) => e.includes('missing dialog key'))).toBe(true);
      expect(errors.some((e) => e.includes('no_such_dialog'))).toBe(true);
    });

    it('reports a playerStart position out of bounds', () => {
      const bad = { ...baseLevel, playerStart: { x: 900, y: 700 } };
      const errors = validateLevelData([bad], realDialogues, textures);
      expect(errors.some((e) => e.includes('playerStart out of bounds'))).toBe(true);
    });

    it('validates the shipped levels, dialogues and textures without errors', () => {
      expect(validateLevelData(realLevels, realDialogues, realTextures)).toEqual([]);
    });
  });
});

// --- Local runner summary ----------------------------------------------------

